#!/usr/bin/env python3
"""Regenerate docs/wiki/field-guide/citations.qmd from the field-guide pages.

Every field-guide page carries inline citation tokens of the form
``{src:<kind>:<ref>}`` and a ``## Sources`` table.  This generator reads each
page, collects the tokens and the table rows, and writes one table per kind
(``pbo``, ``cfg``, ``exe``, ``cmd``, ``adr``, ``probe``, ``script``) with the
page, the reference and the headless check that reproduces it.

The headless check for a token is the ``verify`` cell of the matching
``## Sources`` row.  When no row matches the reference, the page's front-matter
``verify:`` value is used.

Write mode refuses to remove a reference the file already lists unless
``--allow-removals`` is given, so a parser regression cannot silently truncate
the index.  ``--check`` compares the file with the sources and exits non-zero
on drift.

Run from the repo root:

    python3 tools/field-guide/citations.py            # write the file
    python3 tools/field-guide/citations.py --check    # compare, no write
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
GUIDE = REPO / "docs" / "wiki" / "field-guide"
FEATURES = GUIDE / "features"
CEILING = GUIDE / "ceiling.qmd"
DOC = GUIDE / "citations.qmd"

KINDS = ("pbo", "cfg", "exe", "cmd", "adr", "probe", "script")
TOKEN = re.compile(r"\{src:(pbo|cfg|exe|cmd|adr|probe|script):([^}\s]+)\}")

INTRO = (
    "Generated by `tools/field-guide/citations.py`. Do not edit by hand. "
    "Every citation token a field-guide page carries, grouped by kind. The "
    "`Verify` cell names the headless check that reproduces the source: "
    "`extract` (the extraction harness), `strings` (a search over the engine "
    "binary), `test:<path>` (a unittest module), `probe:<P###>` (a Docker "
    "probe), or `kernel:<path>` (a pure-kernel check)."
)


def _pages() -> list[Path]:
    pages = sorted(FEATURES.glob("*.qmd"))
    if CEILING.is_file():
        pages.append(CEILING)
    return pages


def _front_matter(text: str) -> dict[str, str]:
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    fields: dict[str, str] = {}
    for line in text[3:end].splitlines():
        if ":" in line:
            key, _, value = line.partition(":")
            fields[key.strip()] = value.strip()
    return fields


def _source_rows(text: str) -> dict[tuple[str, str], str]:
    """Map (kind, reference) -> verify cell from the ## Sources table."""
    found: dict[tuple[str, str], str] = {}
    lines = text.splitlines()
    try:
        start = next(i for i, line in enumerate(lines) if line.strip() == "## Sources")
    except StopIteration:
        return found
    table = [line for line in lines[start + 1 :] if line.strip().startswith("|")]
    if len(table) < 3:
        return found
    header = [cell.strip().lower() for cell in table[0].strip().strip("|").split("|")]
    if "verify" not in header:
        return found
    verify_col = header.index("verify")
    kind_col = header.index("kind") if "kind" in header else 0
    ref_col = header.index("reference") if "reference" in header else 1
    for row in table[2:]:
        cells = [cell.strip().strip("`") for cell in row.strip().strip("|").split("|")]
        if len(cells) != len(header):
            continue
        found[(cells[kind_col], cells[ref_col])] = cells[verify_col]
    return found


def _page_label(path: Path) -> str:
    return path.relative_to(GUIDE).as_posix()


def collect() -> list[tuple[str, str, str, str]]:
    """Every (page, kind, reference, verify), deduplicated and sorted."""
    rows: set[tuple[str, str, str, str]] = set()
    for path in _pages():
        text = path.read_text(encoding="utf-8")
        verify_map = _source_rows(text)
        default_verify = _front_matter(text).get("verify", "extract")
        label = _page_label(path)
        for kind, ref in TOKEN.findall(text):
            verify = verify_map.get((kind, ref), default_verify)
            rows.add((label, kind, ref, verify))
    return sorted(rows, key=lambda row: (row[1], row[0], row[2]))


def render(rows: list[tuple[str, str, str, str]]) -> str:
    lines: list[str] = [
        "---",
        'title: "Field guide citations"',
        "---",
        "",
        "# Field guide citations {#sec-field-guide-citations}",
        "",
        INTRO,
        "",
    ]
    for kind in KINDS:
        kind_rows = [row for row in rows if row[1] == kind]
        if not kind_rows:
            continue
        lines.append(f"## {kind}")
        lines.append("")
        lines.append("| Page | Reference | Verify |")
        lines.append("|---|---|---|")
        for page, _, ref, verify in kind_rows:
            lines.append(f"| `{page}` | `{ref}` | {verify} |")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def _references_in_doc(text: str) -> set[tuple[str, str, str]]:
    """Every (kind, page, reference) a rendered index already lists."""
    found: set[tuple[str, str, str]] = set()
    kind = ""
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("## "):
            kind = stripped[3:].strip()
            continue
        if kind not in KINDS or not stripped.startswith("|"):
            continue
        cells = [cell.strip().strip("`") for cell in stripped.strip("|").split("|")]
        if len(cells) == 3 and cells[0].endswith(".qmd") and cells[1]:
            found.add((kind, cells[0], cells[1]))
    return found


def check(path: Path = DOC) -> int:
    rendered = render(collect())
    if not path.exists():
        print(f"missing: {path}")
        return 1
    if path.read_text(encoding="utf-8") != rendered:
        print(f"stale: {path}")
        return 1
    print(f"fresh: {path}")
    return 0


def write(path: Path = DOC, allow_removals: bool = False) -> int:
    rows = collect()
    rendered = render(rows)
    if path.exists() and not allow_removals:
        stale = _references_in_doc(path.read_text(encoding="utf-8")) - {
            (row[1], row[0], row[2]) for row in rows
        }
        if stale:
            dropped = ", ".join(
                f"{kind}:{page}:{ref}" for kind, page, ref in sorted(stale)
            )
            print(
                "refusing to write: the new index would drop "
                f"{len(stale)} reference(s): {dropped}"
            )
            return 1
    path.write_text(rendered, encoding="utf-8")
    print(f"wrote {len(rows)} citation row(s) to {path}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare, do not write")
    parser.add_argument(
        "--allow-removals",
        action="store_true",
        help="permit a write that removes an already-listed reference",
    )
    args = parser.parse_args(argv)
    if args.check:
        return check()
    return write(allow_removals=args.allow_removals)


if __name__ == "__main__":
    sys.exit(main())
